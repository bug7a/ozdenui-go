type entry struct {
	Defaults      map[string]any    `json:"defaults"`
	Aliases       map[string]string `json:"aliases"`
	State         map[string]string `json:"state"`
	Sync          []string          `json:"sync"`
	StateDefaults map[string]any    `json:"stateDefaults"`
	DataParams    *[]string         `json:"dataParams"`
	FormatParams  []string          `json:"formatParams"`
	WholeArgs     map[string][]int  `json:"wholeArgs"`
	HasOwnPlace   bool              `json:"hasOwnPlace"`
	Container     string            `json:"container"`
	ContainerHint string            `json:"containerHint"`
	FocusPart     string            `json:"focusPart"`
	OnPage        bool              `json:"onPage"`
	SizeInStyle   bool              `json:"sizeInStyle"`
	DarkStyle     string            `json:"darkStyle"`
	HasMinimal    bool              `json:"hasMinimal"`
	ThemeParam    bool              `json:"themeParam"`
	Doc           string            `json:"doc"`
}

type param struct {
	name    string
	value   string // the text of its default
	comment string
}

const webFolder = "web"

var (
	listLine     = regexp.MustCompile(`(?m)^\s+(\w+): \["([^"]+)"`)
	defaultsLine = regexp.MustCompile(`^( *)const \w*[Dd]efaults = \{[ \t]*$`)
	setMethod    = regexp.MustCompile(`\bbox\.(set[A-Z]\w*)\s*=\s*(?:async\s+)?function\s*\(([^)]*)\)`)
	anyMethod    = regexp.MustCompile(`\bbox\.([a-z]\w*)\s*=\s*(?:async\s+)?(?:function\b|\([^)]*\)\s*=>)`)
	parentOf     = regexp.MustCompile(`startExtendedObject\((\w+),`)
	objectSetter = regexp.MustCompile(`\bset (\w+)\(`)
	// WHY: the page calls them while it draws and needs their answer at once; a function of the program answers later
	notForProgram = regexp.MustCompile(`^(create|update)\w*View$`)
	flagComment   = regexp.MustCompile(`(^|[\s(])[01]\b[,:]`)
	whenToUse     = regexp.MustCompile(`WHEN TO USE IT: ([^\n]+(?:\n[^\n]+)*)`)
	sizeName      = regexp.MustCompile(`(?i)(width|height|size|left|top|right|bottom|gap|padding|round|value|key|count|index)$`)
	// Not components to make: helpers of the kit and the ones with functions of their own in this module.
	noFunction = map[string]bool{"UI": true, "UIEffects": true, "TapEffect": true, "ScrollBar": true, "MinimalAccent": true, "Toast": true}
	// Fields every Props type has besides the params of its component.
	commonFields = []param{
		{"left", "", "with Top: a place of its own in a Box or on the page"},
		{"top", "", ""},
		{"width", "", `120, "100%", "auto"`},
		{"height", "", ""},
		{"styleName", `""`, "the package of its look (see the function)"},
		{"style", "{", `keys of its look, over its package: ozdenui.P{"box": ozdenui.P{"round": 12}}`},
		{"visible", "", ""},
		{"opacity", "", ""},
	}
)

func main() {
	files := componentFiles()
	spec := map[string]*entry{}
	text, err := os.ReadFile(filepath.Join("internal", "gen", "spec.json"))
	check(err)
	check(json.Unmarshal(text, &spec))
	for name := range spec {
		if _, has := files[name]; !has {
			fmt.Fprintf(os.Stderr, "spec.json: %s is not a component of the kit copy\n", name)
			os.Exit(1)
		}
	}

	var out bytes.Buffer
	out.WriteString("/* Bismillah */\n\n// Code generated by internal/gen from the kit copy (web/) and internal/gen/spec.json. DO NOT EDIT.\n")
	out.WriteString("// Copyright 2026 Bugra Ozden <bugra.ozden@gmail.com> (https://bug7a.github.io/)\n// SPDX-License-Identifier: Apache-2.0\n\n")
	out.WriteString("package ozdenui\n\n")

	basic, err := os.ReadFile(filepath.Join(webFolder, "basic", "basic.min.js"))
	check(err)
	version := regexp.MustCompile(`basic\.js \(v([0-9.]+)\)`).FindSubmatch(basic)
	fmt.Fprintf(&out, "// KitVersion is the version of basic.js in this module.\nconst KitVersion = %q\n\n", version[1])
	props := map[string]bool{}
	for _, match := range objectSetter.FindAllSubmatch(basic, -1) {
		props[string(match[1])] = true
	}
	fmt.Fprintf(&out, "// The values of every basic.js object (its setters).\nvar objectProps = %s\n\n", setLiteral(props))

	names := sortedKeys(files)
	var table, types bytes.Buffer
	for _, name := range names {
		source := sourceOf(name, files)
		params := defaultsOf(source)
		if len(params) == 0 && spec[name] == nil {
			continue
		}
		item := spec[name]
		if item == nil {
			item = &entry{}
		}
		writeSpec(&table, name, item, params, source)
		if !noFunction[name] {
			writeType(&types, name, files[name], item, params, source)
		}
	}
	out.WriteString("var kit = map[string]*componentSpec{\n")
	out.Write(table.Bytes())
	out.WriteString("}\n\n")
	out.Write(types.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		_ = os.WriteFile("kit_gen.go", out.Bytes(), 0o644)
		check(fmt.Errorf("kit_gen.go is not Go: %w", err))
	}
	check(os.WriteFile("kit_gen.go", formatted, 0o644))
	fmt.Printf("kit_gen.go: basic.js v%s, %d components\n", version[1], bytes.Count(types.Bytes(), []byte("\nfunc ")))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// The name of a component -> its file, from the list of the loader (components.js).
func componentFiles() map[string]string {
	text, err := os.ReadFile(filepath.Join(webFolder, "components.js"))
	check(err)
	files := map[string]string{}
	for _, match := range listLine.FindAllStringSubmatch(string(text), -1) {
		files[match[1]] = match[2]
	}
	return files
}

// The code of a component and of the component it is made from (startExtendedObject).
func sourceOf(name string, files map[string]string) string {
	text, err := os.ReadFile(filepath.Join(webFolder, files[name]))
	check(err)
	source := strings.ReplaceAll(string(text), "\r\n", "\n") // a checkout of Windows
	if parent := parentOf.FindStringSubmatch(source); parent != nil && parent[1] != name && files[parent[1]] != "" {
		source += "\n" + sourceOf(parent[1], files)
	}
	return source
}

// The params of a component, in the order of the kit: the keys of its defaults blocks, the first one of a name wins.
func defaultsOf(source string) []param {
	params := []param{}
	seen := map[string]bool{}
	lines := strings.Split(source, "\n")
	for i := 0; i < len(lines); i++ {
		start := defaultsLine.FindStringSubmatch(lines[i])
		if start == nil {
			continue
		}
		keyIndent := start[1] + "    "
		keyLine := regexp.MustCompile(`^` + keyIndent + `([A-Za-z_$][\w$]*)\s*:\s*(.*)$`)
		for i++; i < len(lines) && strings.TrimRight(lines[i], " \t\r") != start[1]+"};"; i++ {
			match := keyLine.FindStringSubmatch(lines[i])
			if match == nil || seen[match[1]] {
				continue
			}
			seen[match[1]] = true
			value, comment := splitComment(match[2])
			isOpen := strings.HasSuffix(value, "[") || strings.HasSuffix(value, "{")
			if isOpen && comment == "" && i+1 < len(lines) {
				// A list or a table written over lines: its first line shows how an item is written
				example := strings.TrimSuffix(strings.TrimSpace(lines[i+1]), ",")
				if strings.HasPrefix(example, "{") && strings.HasSuffix(example, "}") {
					comment = "Ex: " + example
				}
			}
			if notForProgram.MatchString(match[1]) {
				continue
			}
			params = append(params, param{match[1], value, comment})
		}
	}
	return params
}

func splitComment(text string) (value, comment string) {
	text = strings.TrimSpace(text)
	if at := strings.Index(text, " // "); at >= 0 {
		comment = strings.TrimSpace(text[at+4:])
		text = strings.TrimSpace(text[:at])
	} else if strings.HasPrefix(text, "// ") {
		return "", strings.TrimSpace(text[3:])
	}
	return strings.TrimSuffix(text, ","), comment
}

func isCallback(item param) bool {
	isName := len(item.name) > 2 && strings.HasPrefix(item.name, "on") && unicode.IsUpper(rune(item.name[2]))
	return isName || strings.HasPrefix(item.value, "function") || strings.Contains(item.value, "=>")
}

func writeSpec(out *bytes.Buffer, name string, item *entry, params []param, source string) {
	names := map[string]bool{}
	for _, item := range params {
		names[item.name] = true
	}
	methods := map[string]bool{}
	for _, match := range anyMethod.FindAllStringSubmatch(source, -1) {
		methods[match[1]] = true
	}
	setters := []string{}
	for _, match := range setMethod.FindAllStringSubmatch(source, -1) {
		paramName := strings.ToLower(match[1][3:4]) + match[1][4:]
		if !names[paramName] {
			continue
		}
		arguments := strings.Split(match[2], ",")
		isSilent := len(arguments) > 1 && strings.TrimSpace(strings.Split(arguments[1], "=")[0]) == "silent"
		setters = append(setters, fmt.Sprintf("%q: {%q, %v}", paramName, match[1], isSilent))
	}
	sort.Strings(setters)
	setters = unique(setters)

	fmt.Fprintf(out, "%q: {\nName: %q,\nParams: %s,\nMethods: %s,\n", name, name, setLiteral(names), setLiteral(methods))
	if len(setters) > 0 {
		fmt.Fprintf(out, "Setters: map[string]setter{%s},\n", strings.Join(setters, ", "))
	}
	writeValue(out, "Defaults", item.Defaults, len(item.Defaults) > 0)
	writeValue(out, "Aliases", item.Aliases, len(item.Aliases) > 0)
	writeValue(out, "State", item.State, len(item.State) > 0)
	writeValue(out, "Sync", item.Sync, len(item.Sync) > 0)
	writeValue(out, "StateDefaults", item.StateDefaults, len(item.StateDefaults) > 0)
	if item.DataParams != nil {
		fmt.Fprintf(out, "DataParams: %s,\n", goLiteral(*item.DataParams))
	}
	writeValue(out, "FormatParams", item.FormatParams, len(item.FormatParams) > 0)
	writeValue(out, "WholeArgs", item.WholeArgs, len(item.WholeArgs) > 0)
	writeValue(out, "HasOwnPlace", item.HasOwnPlace, item.HasOwnPlace)
	writeValue(out, "Container", item.Container, item.Container != "")
	writeValue(out, "ContainerHint", item.ContainerHint, item.ContainerHint != "")
	writeValue(out, "FocusPart", item.FocusPart, item.FocusPart != "")
	writeValue(out, "OnPage", item.OnPage, item.OnPage)
	writeValue(out, "SizeInStyle", item.SizeInStyle, item.SizeInStyle)
	writeValue(out, "DarkStyle", item.DarkStyle, item.DarkStyle != "")
	writeValue(out, "HasMinimal", item.HasMinimal, item.HasMinimal)
	writeValue(out, "ThemeParam", item.ThemeParam, item.ThemeParam)
	out.WriteString("},\n")
}

func writeValue(out *bytes.Buffer, name string, value any, isGiven bool) {
	if isGiven {
		fmt.Fprintf(out, "%s: %s,\n", name, goLiteral(value))
	}
}

func writeType(out *bytes.Buffer, name, file string, item *entry, params []param, source string) {
	doc := item.Doc
	if doc == "" {
		doc = fmt.Sprintf("%s makes the %s of the kit (%s).", name, name, file)
	}
	lines := []string{doc}
	if use := whenToUse.FindStringSubmatch(source); use != nil && item.Doc == "" {
		text := strings.Join(strings.Fields(use[1]), " ")
		if end := strings.Index(text, ". "); end > 0 {
			text = text[:end+1]
		}
		lines = append(lines, "When to use it: "+text)
	}
	if looks := looksOf(name, source); len(looks) > 0 {
		lines = append(lines, "StyleName: "+strings.Join(looks, ", ")+".")
	}
	if item.DarkStyle != "" || item.ThemeParam {
		lines = append(lines, "A dark window gives it its dark look.")
	}
	if len(item.State) > 0 {
		lines = append(lines, "Read without a question to the page: "+readable(item.State)+".")
	}
	if item.ContainerHint != "" {
		lines = append(lines, "Objects go into it with "+item.ContainerHint+".")
	}
	if methods := publicMethods(source); len(methods) > 0 {
		lines = append(lines, "Methods of the kit, for obj.Call() and obj.Ask() (its file tells what each takes): "+strings.Join(methods, ", ")+".")
	}

	fmt.Fprintf(out, "// %sProps are the params of a %s, by their names in the kit (%s). A param that is not given keeps\n// the default written next to it.\n", name, name, file)
	fmt.Fprintf(out, "type %sProps struct {\n", name)
	seen := map[string]bool{}
	spec := item
	isFormat := map[string]bool{}
	for _, name := range item.FormatParams {
		isFormat[name] = true
	}
	writeField := func(item param, isCommon bool) {
		field := fieldName(item.name)
		if seen[field] {
			return
		}
		seen[field] = true
		kind := "any"
		switch {
		case isCallback(item):
			kind = "any"
		case sizeName.MatchString(item.name) || flagComment.MatchString(item.comment):
			kind = "any" // a number or a text ("100%"), also where the default is a text
		case strings.HasPrefix(item.value, `"`) || strings.HasPrefix(item.value, `'`) || strings.HasPrefix(item.value, "`"):
			kind = "string"
		case strings.HasPrefix(item.value, "{") && item.name != "value":
			kind = "P"
		}
		tag := ""
		if kitNameOf(field) != item.name {
			tag = fmt.Sprintf(" `ui:%q`", item.name)
		}
		note := []string{}
		if own, has := spec.Defaults[item.name]; has {
			text, _ := json.Marshal(own)
			note = append(note, "default: "+string(text)+" (the kit alone: "+shortValue(item)+")")
		} else if !isCommon && item.value != "" {
			note = append(note, "default: "+shortValue(item))
		}
		if isFormat[item.name] {
			item.comment = `a Format text, made by the page at once: "{:,.2f} TL", "{:.0f} kg", "{:.1%}" (not a function)`
		}
		if item.comment != "" {
			note = append(note, item.comment)
		}
		comment := ""
		if len(note) > 0 {
			comment = " // " + strings.Join(note, ". ")
		}
		fmt.Fprintf(out, "%s %s%s%s\n", field, kind, tag, comment)
	}
	for _, item := range params {
		writeField(item, false)
	}
	out.WriteString("\n")
	for _, item := range commonFields {
		writeField(item, true)
	}
	if item.FocusPart != "" && !seen["OnEnter"] {
		out.WriteString("OnEnter any // the Enter key: func() or func(field *ozdenui.Object)\n")
	}
	out.WriteString("Fill bool // it takes the room the other objects of its group leave\n")
	out.WriteString("Unframed bool // no border and no rounded corners on its box (it fills the room between two bars)\n")
	out.WriteString("Extra P // any other value, by its name in the kit\n}\n\n")

	for i, line := range lines {
		if i > 0 {
			out.WriteString("//\n") // a paragraph of its own in go doc
		}
		fmt.Fprintf(out, "// %s\n", line)
	}
	if item.Container != "" {
		fmt.Fprintf(out, "func %s(props %sProps, content ...func()) *Object { return makeTyped(%q, props, content) }\n\n", name, name, name)
		return
	}
	fmt.Fprintf(out, "func %s(props %sProps) *Object { return makeTyped(%q, props, nil) }\n\n", name, name, name)
}

// The methods a program may call: not the inner steps of the component (the kit keeps them on the box too).
func publicMethods(source string) []string {
	inner := regexp.MustCompile(`^(create|update|calc|apply|render|draw|refresh|paint|handle|on[A-Z]|build|make|layout|init|_)`)
	methods := map[string]bool{}
	for _, match := range anyMethod.FindAllStringSubmatch(source, -1) {
		if !inner.MatchString(match[1]) {
			methods[match[1]] = true
		}
	}
	return sortedKeys(methods)
}

// The packages of looks of a component: X.styles = { light: ..., dark: ... } and X.styles.name = ...
func looksOf(name, source string) []string {
	looks := map[string]bool{}
	for _, match := range regexp.MustCompile(`(?m)^`+name+`\.styles\.(\w+)\s*=`).FindAllStringSubmatch(source, -1) {
		looks[match[1]] = true
	}
	lines := strings.Split(source, "\n")
	for i := 0; i < len(lines); i++ {
		if !strings.HasPrefix(lines[i], name+".styles = {") {
			continue
		}
		for i++; i < len(lines) && !strings.HasPrefix(lines[i], "}"); i++ {
			if match := regexp.MustCompile(`^    (\w+)\s*:`).FindStringSubmatch(lines[i]); match != nil {
				looks[match[1]] = true
			}
		}
	}
	return sortedKeys(looks)
}

func readable(state map[string]string) string {
	names := []string{}
	for _, name := range sortedKeys(state) {
		names = append(names, fmt.Sprintf(`obj.Get("%s")`, name))
	}
	return strings.Join(names, ", ")
}

func shortValue(item param) string {
	value := item.value
	if isCallback(item) {
		return "a function"
	}
	if strings.HasSuffix(value, "{") {
		return value + "...}"
	}
	if strings.HasSuffix(value, "[") {
		return value + "...]"
	}
	if len(value) > 60 {
		value = value[:57] + "..."
	}
	return value
}

// labelText -> LabelText, lbl_arrow -> LblArrow, $x -> X
func fieldName(name string) string {
	parts := strings.FieldsFunc(name, func(letter rune) bool { return letter == '_' || letter == '$' })
	for i, part := range parts {
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	return strings.Join(parts, "")
}

// As kitName() of values.go: the name the module reads from a field without a tag.
func kitNameOf(field string) string {
	runes := []rune(field)
	for i := range runes {
		isLastOfUpperRun := i > 0 && i+1 < len(runes) && unicode.IsLower(runes[i+1])
		if !unicode.IsUpper(runes[i]) || isLastOfUpperRun {
			break
		}
		runes[i] = unicode.ToLower(runes[i])
	}
	return string(runes)
}

func setLiteral(names map[string]bool) string {
	items := []string{}
	for _, name := range sortedKeys(names) {
		items = append(items, fmt.Sprintf("%q: true", name))
	}
	return "map[string]bool{" + strings.Join(items, ", ") + "}"
}

func goLiteral(value any) string {
	switch typed := value.(type) {
	case nil:
		return "nil"
	case string:
		return fmt.Sprintf("%q", typed)
	case bool:
		return fmt.Sprint(typed)
	case float64:
		return fmt.Sprint(typed)
	case []string:
		items := []string{}
		for _, item := range typed {
			items = append(items, fmt.Sprintf("%q", item))
		}
		return "[]string{" + strings.Join(items, ", ") + "}"
	case map[string]string:
		items := []string{}
		for _, key := range sortedKeys(typed) {
			items = append(items, fmt.Sprintf("%q: %q", key, typed[key]))
		}
		return "map[string]string{" + strings.Join(items, ", ") + "}"
	case map[string][]int:
		items := []string{}
		for _, key := range sortedKeys(typed) {
			items = append(items, fmt.Sprintf("%q: %#v", key, typed[key]))
		}
		return "map[string][]int{" + strings.Join(items, ", ") + "}"
	case []any:
		items := []string{}
		for _, item := range typed {
			items = append(items, goLiteral(item))
		}
		return "[]any{" + strings.Join(items, ", ") + "}"
	case map[string]any:
		items := []string{}
		for _, key := range sortedKeys(typed) {
			items = append(items, fmt.Sprintf("%q: %s", key, goLiteral(typed[key])))
		}
		return "P{" + strings.Join(items, ", ") + "}"
	}
	panic(fmt.Sprintf("spec.json: a value of the type %T", value))
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func unique(items []string) []string {
	result := []string{}
	for i, item := range items {
		if i == 0 || item != items[i-1] {
			result = append(result, item)
		}
	}
	return result
}
